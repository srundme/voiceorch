"""Build artifacts/api-server/src/data/star-premiums.ts from the Star premium chart transcriptions.

Usage: python3 scripts/build-star-premiums.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs/star-health-kb/vision/premium"
OUT = ROOT / "artifacts/api-server/src/data/star-premiums.ts"


def lakh(col: str) -> float | None:
    col = col.strip()
    if col.endswith(" L"):
        return float(col[:-2])
    if col.endswith(" Cr"):
        return float(col[:-3]) * 100
    return None  # "Unlimited" and other non-numeric columns are dropped


def band(label: str) -> list[int]:
    s = label.strip().replace("–", "-")
    if s.lower().startswith("above"):
        return [int(re.sub(r"\D", "", s)) + 1, 200]
    if "-" not in s:
        n = int(s)
        return [n, n]
    lo, hi = s.split("-", 1)
    lo_n = 0 if re.search(r"m|days", lo) else int(re.sub(r"\D", "", lo))
    return [lo_n, int(re.sub(r"\D", "", hi))]


def parse_table(lines: list[str]) -> dict:
    rows = [l for l in lines if l.startswith("|")]
    head = [c.strip() for c in rows[0].strip("|").split("|")]
    cols = [(i, lakh(c)) for i, c in enumerate(head) if i > 0 and lakh(c) is not None]
    bands = []
    for r in rows[2:]:
        cells = [c.strip() for c in r.strip("|").split("|")]
        bands.append({
            "age": band(cells[0]),
            "premium": [int(cells[i].replace(",", "")) for i, _ in cols],
        })
    return {"sumInsuredLakh": [v for _, v in cols], "bands": bands}


def sections(text: str, level: str) -> list[tuple[str, str]]:
    parts = re.split(rf"^{level} (.+)$", text, flags=re.M)
    return [(parts[i].strip(), parts[i + 1]) for i in range(1, len(parts), 2)]


def family_charts(path: Path) -> dict:
    zones = {}
    for zone_title, body in sections(path.read_text(), "##"):
        zone = zone_title.split()[-1]
        zones[zone] = {}
        for title, tbody in sections(body, "###"):
            family = title.split("—")[-1].strip()
            zones[zone][family] = parse_table(tbody.splitlines())
    return zones


def super_star(path: Path) -> dict:
    zones = {}
    for zone_title, body in sections(path.read_text(), "##"):
        zone = zone_title.split()[-1]
        tables = {}
        for title, tbody in sections(body, "###"):
            key = "individual" if title.startswith("Individual") else "floaterAdult" if "adult" in title else "floaterChild"
            tables[key] = parse_table(tbody.splitlines())
        zones[zone] = tables
    return zones


data = {
    "superStar": super_star(SRC / "super-star-premium.md"),
    "comprehensive": family_charts(SRC / "comprehensive-premium.md"),
    "healthAssure": family_charts(SRC / "health-assure-premium.md"),
}

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(
    "// Generated by scripts/build-star-premiums.py from docs/star-health-kb/vision/premium. Do not edit by hand.\n"
    "// Yearly premium in rupees, excluding GST, base cover. Ages are inclusive [min, max].\n\n"
    "import type { StarPremiumData } from \"../services/star-premium.js\";\n\n"
    f"export const STAR_PREMIUMS: StarPremiumData = {json.dumps(data, separators=(',', ':'))};\n"
)
print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")
for plan, zones in data.items():
    print(plan, {z: sorted(t) for z, t in zones.items()})
