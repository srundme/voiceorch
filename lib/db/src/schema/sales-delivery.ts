import { pgTable, serial, integer, text, timestamp, jsonb, boolean, uniqueIndex, index } from "drizzle-orm/pg-core";
import { salesCompaniesTable } from "./sales-pipeline";

export const salesPilotsTable = pgTable("sales_pilots", {
  id: serial("id").primaryKey(),
  companyId: integer("company_id").notNull().references(() => salesCompaniesTable.id, { onDelete: "cascade" }),
  opportunityId: integer("opportunity_id"),
  status: text("status").notNull().default("Draft"),
  useCase: text("use_case"),
  language: text("language"),
  qualificationCriteria: text("qualification_criteria"),
  approvedScript: text("approved_script"),
  leadCount: integer("lead_count"),
  contactBasisConfirmed: boolean("contact_basis_confirmed").notNull().default(false),
  campaignRef: text("campaign_ref"),
  reportLink: text("report_link"),
  recordingLinks: jsonb("recording_links"),
  onboardingStartedAt: timestamp("onboarding_started_at", { withTimezone: true }),
  campaignStartedAt: timestamp("campaign_started_at", { withTimezone: true }),
  windowStart: timestamp("window_start", { withTimezone: true }),
  windowEnd: timestamp("window_end", { withTimezone: true }),
  reviewAt: timestamp("review_at", { withTimezone: true }),
  ownerId: integer("owner_id"),
  followupOwnerId: integer("followup_owner_id"),
  attemptAllowance: integer("attempt_allowance").notNull().default(200),
  extensionAttempts: integer("extension_attempts"),
  extensionReason: text("extension_reason"),
  extensionCostLimitPaise: integer("extension_cost_limit_paise"),
  extensionReviewAt: timestamp("extension_review_at", { withTimezone: true }),
  extensionApprovedBy: integer("extension_approved_by"),
  capacityOverrideReason: text("capacity_override_reason"),
  capacityOverrideBy: integer("capacity_override_by"),
  readiness: jsonb("readiness"),
  qualityReview: jsonb("quality_review"),
  buyerFeedback: text("buyer_feedback"),
  acceptedOutcomesNote: text("accepted_outcomes_note"),
  proposedNextStep: text("proposed_next_step"),
  customerReportNotes: text("customer_report_notes"),
  internalNotes: text("internal_notes"),
  cancelledReason: text("cancelled_reason"),
  isDemo: boolean("is_demo").notNull().default(false),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  completedAt: timestamp("completed_at", { withTimezone: true }),
}, (t) => [
  index("sales_pilots_company_idx").on(t.companyId),
  index("sales_pilots_status_idx").on(t.status),
]);

export const salesPilotSnapshotsTable = pgTable("sales_pilot_snapshots", {
  id: serial("id").primaryKey(),
  pilotId: integer("pilot_id").notNull().references(() => salesPilotsTable.id, { onDelete: "cascade" }),
  snapshotKey: text("snapshot_key").notNull(),
  asOf: timestamp("as_of", { withTimezone: true }).notNull(),
  source: text("source").notNull().default("manual"),
  attempts: integer("attempts").notNull().default(0),
  distinctRecords: integer("distinct_records").notNull().default(0),
  answered: integer("answered").notNull().default(0),
  meaningful: integer("meaningful").notNull().default(0),
  qualifiedPeople: integer("qualified_people").notNull().default(0),
  acceptedOutcomes: integer("accepted_outcomes").notNull().default(0),
  callbackRequests: integer("callback_requests").notNull().default(0),
  confirmedAppointments: integer("confirmed_appointments").notNull().default(0),
  connectedMinutes: integer("connected_minutes").notNull().default(0),
  costPaise: integer("cost_paise").notNull().default(0),
  createdBy: integer("created_by"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
}, (t) => [uniqueIndex("sales_pilot_snapshots_key_uq").on(t.pilotId, t.snapshotKey)]);

export type SalesPilot = typeof salesPilotsTable.$inferSelect;
export type SalesPilotSnapshot = typeof salesPilotSnapshotsTable.$inferSelect;
