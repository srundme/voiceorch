export function getIntakeJob(id: string | null | undefined): IntakeJob | null {
  if (!id) return null;
  return INTAKE_JOBS.find((j) => j.id === id) ?? null;
}

export function intakeJobProcesses(): string[] {
  return [...new Set(INTAKE_JOBS.map((j) => j.process))].sort();
}
